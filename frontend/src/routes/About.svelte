  <h1>About RaaGamaalika</h1>
  <p>RaaGamaalika listens to a Carnatic performance and suggests the raga.</p>
  <h2>Confident answer or shortlist?</h2>
  <p>
    You get a <strong>confident answer</strong> only when the app's example recordings clearly point to one raga
    <em>and</em> the swaras it heard fit that raga's arohana and avarohana. Otherwise it gives an honest
    <strong>shortlist</strong> ("Likely one of…"). Ragas that use exactly the same swaras are marked
    "These ragas share the same swaras" — telling them apart needs characteristic phrases, which this
    early version can't yet judge.
  </p>
  <h2>Shruti</h2>
  <p>
    The app detects the performer's Sa. If the swaras fit much better with a different Sa it asks
    "Check the shruti?" — you can accept the suggestion or pick the shruti yourself.
  </p>
  <h2>Privacy</h2>
  <p>Audio you record or upload is analysed and immediately discarded. Your recent results stay on this device.</p>
